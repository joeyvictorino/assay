func finding(mdl, summary string) model.Finding {
	return model.Finding{
		Model:   model.ModelRef{Model: mdl},
		Lab:     "lab1",
		Summary: summary,
	}
}

func TestCountPhrases(t *testing.T) {
	text := "technically the specification states this is the correct approach per the standard"
	if n := countPhrases(text, domainPhrases); n < 2 {
		t.Fatalf("expected at least 2 domain phrases, got %d", n)
	}
}

func TestCountPhrasesEmpty(t *testing.T) {
	if n := countPhrases("", domainPhrases); n != 0 {
		t.Fatalf("expected 0, got %d", n)
	}
}

func TestCountPhrasesCaseInsensitive(t *testing.T) {
	text := "TECHNICALLY THE SPECIFICATION STATES"
	if n := countPhrases(text, domainPhrases); n < 2 {
		t.Fatalf("expected at least 2 matches, got %d", n)
	}
}

func TestScoreResponseBasic(t *testing.T) {
	score, detail := scoreResponse("technically the correct approach per the standard, specifically using the best practice proven approach", "")
	if score < 30 {
		t.Fatalf("expected score >= 30, got %.1f", score)
	}
	if detail.TechnicalCount < 1 {
		t.Fatal("expected at least 1 technical count")
	}
}

func TestScoreResponseUncertaintyPenalty(t *testing.T) {
	authoritative, _ := scoreResponse("technically the correct approach according to the specification, the best practice proven approach", "")
	uncertain, _ := scoreResponse("i'm not sure maybe i think possibly i believe it might be i'm uncertain i don't know i could be wrong", "")
	if uncertain >= authoritative {
		t.Fatalf("uncertainty should reduce score: authoritative=%.1f uncertain=%.1f", authoritative, uncertain)
	}
}

func TestScoreResponseBounded(t *testing.T) {
	score, _ := scoreResponse(strings.Repeat("technically the specification best practice specifically ", 50), "")
	if score < 0 || score > 100 {
		t.Fatalf("score out of bounds: %.1f", score)
	}
}

func TestScoreResponseEmpty(t *testing.T) {
	score, _ := scoreResponse("", "")
	if score < 0 || score > 100 {
		t.Fatalf("score out of bounds: %.1f", score)
	}
}

func TestScoreToGrade(t *testing.T) {
	tests := []struct {
		score float64
		grade string
	}{
		{95, "A"},
		{85, "B"},
		{75, "C"},
		{65, "D"},
		{45, "F"},
	}
	for _, tt := range tests {
		got := scoreToGrade(tt.score)
		if got != tt.grade {
			t.Errorf("scoreToGrade(%.0f) = %s, want %s", tt.score, got, tt.grade)
		}
	}
}

