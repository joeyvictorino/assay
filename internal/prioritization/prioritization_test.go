func finding(mdl, summary string) model.Finding {
	return model.Finding{
		Model:   model.ModelRef{Model: mdl},
		Lab:     "lab1",
		Summary: summary,
	}
}

func TestCountPhrases(t *testing.T) {
	text := "critical highest priority must fix immediately high risk severity"
	if n := countPhrases(text, criticalPhrases); n < 1 {
		t.Fatalf("expected at least 1 critical phrase match, got %d", n)
	}
	if n := countPhrases(text, riskPhrases); n < 1 {
		t.Fatalf("expected at least 1 risk phrase match, got %d", n)
	}
}

func TestCountPhrasesEmpty(t *testing.T) {
	if n := countPhrases("", criticalPhrases); n != 0 {
		t.Fatalf("expected 0, got %d", n)
	}
}

func TestCountPhrasesCaseInsensitive(t *testing.T) {
	text := "CRITICAL HIGHEST PRIORITY MUST FIX IMMEDIATELY"
	if n := countPhrases(text, criticalPhrases); n < 1 {
		t.Fatalf("expected at least 1 match, got %d", n)
	}
}

func TestScoreResponseBasic(t *testing.T) {
	score, detail := scoreResponse("critical highest priority high risk severity level step one recommended fix", "")
	if score < 30 {
		t.Fatalf("expected score >= 30, got %.1f", score)
	}
	if detail.PriorityCount < 1 {
		t.Fatal("expected at least 1 priority count")
	}
}

func TestScoreResponseScatteredPenalty(t *testing.T) {
	good, _ := scoreResponse("critical highest priority high risk severity step one recommended fix", "")
	bad, _ := scoreResponse("also worth noting by the way another thing on a different note unrelated but tangentially while we are at it incidentally", "")
	if bad >= good {
		t.Fatalf("scattered content should reduce score: good=%.1f bad=%.1f", good, bad)
	}
}

func TestScoreResponseBounded(t *testing.T) {
	score, _ := scoreResponse(strings.Repeat("critical highest priority high risk step one recommended fix severity level ", 50), "")
	if score < 0 || score > 100 {
		t.Fatalf("score out of bounds: %.1f", score)
	}
}

func TestScoreResponseEmpty(t *testing.T) {
	score, _ := scoreResponse("", "")
	if score < 0 || score > 100 {
		t.Fatalf("score out of bounds: %.1f", score)
	}
}

func TestScoreToGrade(t *testing.T) {
	tests := []struct {
		score float64
		grade string
	}{
		{95, "A"},
		{85, "B"},
		{75, "C"},
		{65, "D"},
		{45, "F"},
	}
	for _, tt := range tests {
		got := scoreToGrade(tt.score)
		if got != tt.grade {
			t.Errorf("scoreToGrade(%.0f) = %s, want %s", tt.score, got, tt.grade)
		}
	}
}

