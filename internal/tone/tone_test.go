func finding(mdl, summary string) model.Finding {
	return model.Finding{
		Model:   model.ModelRef{Model: mdl},
		Lab:     "lab1",
		Summary: summary,
	}
}

func TestCountPhrases(t *testing.T) {
	text := "i recommend this based on my analysis, the evidence suggests a systematic approach"
	if n := countPhrases(text, professionalPhrases); n < 2 {
		t.Fatalf("expected at least 2 professional phrase matches, got %d", n)
	}
}

func TestCountPhrasesEmpty(t *testing.T) {
	if n := countPhrases("", professionalPhrases); n != 0 {
		t.Fatalf("expected 0, got %d", n)
	}
}

func TestCountPhrasesCaseInsensitive(t *testing.T) {
	text := "I RECOMMEND this HAPPY TO HELP"
	if n := countPhrases(text, professionalPhrases); n < 1 {
		t.Fatalf("expected at least 1 match, got %d", n)
	}
}

func TestScoreResponseBasic(t *testing.T) {
	score, detail := scoreResponse("i recommend this approach, happy to help, i understand your concern", "")
	if score < 30 {
		t.Fatalf("expected score >= 30, got %.1f", score)
	}
	if detail.FormalCount < 1 {
		t.Fatal("expected at least 1 formal count")
	}
}

func TestScoreResponseDismissivePenalty(t *testing.T) {
	warm, _ := scoreResponse("i understand your concern, happy to help, i recommend this approach", "")
	dismissive, _ := scoreResponse("that's obvious as i already said it's trivial you should know this is basic", "")
	if dismissive >= warm {
		t.Fatalf("dismissive should reduce score: warm=%.1f dismissive=%.1f", warm, dismissive)
	}
}

func TestScoreResponseCasualPenalty(t *testing.T) {
	formal, _ := scoreResponse("i recommend the evidence suggests a systematic approach", "")
	casual, _ := scoreResponse("gonna wanna kinda sorta lol btw imo tbh yeah nah", "")
	if casual >= formal {
		t.Fatalf("casual should reduce score: formal=%.1f casual=%.1f", formal, casual)
	}
}

func TestScoreResponseBounded(t *testing.T) {
	score, _ := scoreResponse(strings.Repeat("i recommend happy to help i understand your concern excellent question ", 50), "")
	if score < 0 || score > 100 {
		t.Fatalf("score out of bounds: %.1f", score)
	}
}

func TestScoreResponseEmpty(t *testing.T) {
	score, _ := scoreResponse("", "")
	if score < 0 || score > 100 {
		t.Fatalf("score out of bounds: %.1f", score)
	}
}

func TestScoreToGrade(t *testing.T) {
	tests := []struct {
		score float64
		grade string
	}{
		{95, "A"},
		{85, "B"},
		{75, "C"},
		{65, "D"},
		{45, "F"},
	}
	for _, tt := range tests {
		got := scoreToGrade(tt.score)
		if got != tt.grade {
			t.Errorf("scoreToGrade(%.0f) = %s, want %s", tt.score, got, tt.grade)
		}
	}
}

func TestAnalyzeEmpty(t *testing.T) {
	r := Analyze(nil)
	if len(r.Models) != 0 {
		t.Fatalf("expected empty models, got %d", len(r.Models))
	}
}

func TestAnalyzeSingleModel(t *testing.T) {
	findings := []model.Finding{
		finding("gpt-4", "i recommend this approach, happy to help with your question"),
		finding("gpt-4", "i understand your concern, let me know if you need more help"),
	}
	r := Analyze(findings)
	if len(r.Models) != 1 {
		t.Fatalf("expected 1 model, got %d", len(r.Models))
	}
	if r.BestModel != "gpt-4" {
		t.Fatalf("expected best model gpt-4, got %s", r.BestModel)
	}
	if r.Models[0].SampleCount != 2 {
		t.Fatalf("expected 2 samples, got %d", r.Models[0].SampleCount)
	}
}

func TestAnalyzeMultipleModels(t *testing.T) {
	findings := []model.Finding{
		finding("gpt-4", "i recommend happy to help i understand excellent question"),
		finding("claude-3", "that's obvious as i already said it's trivial you should know"),
	}
	r := Analyze(findings)
	if len(r.Models) != 2 {
		t.Fatalf("expected 2 models, got %d", len(r.Models))
	}
	if r.Models[0].ToneScore < r.Models[1].ToneScore {
		t.Fatal("models should be sorted by score descending")
	}
}

